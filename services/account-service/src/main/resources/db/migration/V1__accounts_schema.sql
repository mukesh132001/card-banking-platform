-- Customers, accounts and card transactions. Plain SQL that runs on PostgreSQL and on H2 in PostgreSQL mode.

create table customer (
    id          bigint generated by default as identity primary key,
    email       varchar(255) not null unique,
    full_name   varchar(200) not null,
    created_at  timestamp with time zone not null default current_timestamp
);

create table account (
    id              bigint generated by default as identity primary key,
    customer_id     bigint         not null references customer (id),
    account_number  varchar(34)    not null unique,
    type            varchar(20)    not null,   -- CHECKING, SAVINGS, CREDIT_CARD
    currency        varchar(3)     not null,
    balance         numeric(19, 2) not null default 0,
    status          varchar(20)    not null,   -- ACTIVE, FROZEN, CLOSED
    opened_at       timestamp with time zone not null default current_timestamp,
    version         bigint         not null default 0,   -- optimistic locking for balance updates
    constraint ck_account_type     check (type in ('CHECKING', 'SAVINGS', 'CREDIT_CARD')),
    constraint ck_account_status   check (status in ('ACTIVE', 'FROZEN', 'CLOSED')),
    constraint ck_account_currency check (char_length(currency) = 3)
);

create index ix_account_customer on account (customer_id);

-- "transaction" is a reserved word in several databases, so the table is card_transaction.
create table card_transaction (
    id             bigint generated by default as identity primary key,
    account_id     bigint         not null references account (id),
    posted_at      timestamp with time zone not null,
    direction      varchar(6)     not null,   -- CREDIT (money in) or DEBIT (money out)
    amount         numeric(19, 2) not null,   -- always positive; direction gives the sign
    description    varchar(255)   not null,
    merchant       varchar(120),
    category       varchar(40),
    balance_after  numeric(19, 2) not null,
    constraint ck_txn_direction check (direction in ('CREDIT', 'DEBIT')),
    constraint ck_txn_amount    check (amount > 0)
);

create index ix_txn_account_posted on card_transaction (account_id, posted_at desc);
