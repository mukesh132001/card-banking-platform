-- Logins and refresh tokens. A CUSTOMER user is linked to one customer; an ADMIN user has none.

create table app_user (
    id               bigint generated by default as identity primary key,
    email            varchar(255) not null unique,
    password_hash    varchar(100) not null,               -- BCrypt
    role             varchar(20)  not null,
    customer_id      bigint references customer (id),
    failed_attempts  int          not null default 0,
    locked_until     timestamp with time zone,
    created_at       timestamp with time zone not null default current_timestamp,
    constraint ck_user_role check (role in ('CUSTOMER', 'ADMIN')),
    constraint ck_customer_user_has_customer check (role <> 'CUSTOMER' or customer_id is not null)
);

-- Only a SHA-256 hash of each refresh token is stored, so a database leak doesn't leak usable tokens.
create table refresh_token (
    id          bigint generated by default as identity primary key,
    user_id     bigint      not null references app_user (id),
    token_hash  varchar(64) not null unique,
    expires_at  timestamp with time zone not null,
    revoked_at  timestamp with time zone,
    created_at  timestamp with time zone not null default current_timestamp
);

create index ix_refresh_token_user on refresh_token (user_id);
